// Regenerates src/lib/logos.generated.ts from simple-icons (CC0) for the slugs used by presets.
// Usage: node scripts/gen-logos.mjs
import * as si from 'simple-icons';
import { readFileSync, writeFileSync } from 'node:fs';

const presets = readFileSync(new URL('../src/lib/presets.ts', import.meta.url), 'utf8');
const slugs = [...new Set([...presets.matchAll(/logo: '([a-z0-9]+)'/g)].map((m) => m[1]))].sort();
const bySlug = new Map(Object.values(si).filter((x) => x && x.slug).map((x) => [x.slug, x]));

const lines = slugs.map((slug) => {
  const icon = bySlug.get(slug);
  if (!icon) throw new Error(`simple-icons has no "${slug}"`);
  return `  ${JSON.stringify(slug)}: ${JSON.stringify(icon.path)},`;
});

writeFileSync(
  new URL('../src/lib/logos.generated.ts', import.meta.url),
  `// Generated by scripts/gen-logos.mjs from simple-icons (CC0). Do not edit.\n// Brand marks belong to their owners; used only to identify the service.\nexport const LOGO_PATHS: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`wrote ${slugs.length} logos`);
